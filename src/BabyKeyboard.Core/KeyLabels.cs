namespace BabyKeyboard.Core;

public static class KeyLabels
{
    public static string For(int vk) => vk switch
    {
        >= 0x41 and <= 0x5A => ((char)vk).ToString(),
        >= 0x30 and <= 0x39 => ((char)vk).ToString(),
        >= 0x60 and <= 0x69 => (vk - 0x60).ToString(),
        >= 0x70 and <= 0x87 => $"F{vk - 0x6F}",
        0x08 => "退格", 0x09 => "Tab", 0x0D => "回车", 0x20 => "空格",
        0x1B => "Esc", 0x10 or 0xA0 or 0xA1 => "Shift",
        0x11 or 0xA2 or 0xA3 => "Ctrl", 0x12 or 0xA4 or 0xA5 => "Alt",
        0x5B or 0x5C => "Win", 0x14 => "Caps", 0x90 => "Num",
        0x91 => "Scroll", 0x13 => "Pause", 0x2C => "截图", 0x5D => "菜单",
        0x25 => "←", 0x26 => "↑", 0x27 => "→", 0x28 => "↓",
        0x21 => "PgUp", 0x22 => "PgDn", 0x23 => "End", 0x24 => "Home",
        0x2D => "Ins", 0x2E => "Del", 0x6A => "×", 0x6B => "+",
        0x6D => "−", 0x6E => ".", 0x6F => "÷", 0xBA => ";", 0xBB => "=",
        0xBC => ",", 0xBD => "−", 0xBE => ".", 0xBF => "/", 0xC0 => "~",
        0xDB => "[", 0xDC or 0xE2 => "\\", 0xDD => "]", 0xDE => "'",
        0xAD => "静音", 0xAE => "音量 −", 0xAF => "音量 +",
        0xB0 => "下一首", 0xB1 => "上一首", 0xB2 => "停止", 0xB3 => "播放",
        0xA6 => "后退", 0xA7 => "前进", 0xA8 => "刷新", 0xAC => "主页",
        0x15 => "输入", 0x19 => "输入", 0xE5 => "输入",
        _ => "✦"
    };
}
